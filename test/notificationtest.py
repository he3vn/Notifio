def notify_windows(title, body, url):
    import winreg
    from winotify import Notification, audio
 
    # register the app id so Windows 10/11 reliably shows the toast
    with winreg.CreateKey(winreg.HKEY_CURRENT_USER,
                          r"Software\Classes\AppUserModelId\NotifTest") as k:
        winreg.SetValueEx(k, "DisplayName", 0, winreg.REG_SZ, "Notif Test")
 
    toast = Notification(app_id="NotifTest", title=title, msg=body,
                         duration="short", launch=url)
    toast.set_audio(audio.Silent, loop=False)
    toast.show()
 
 
def send(title=TITLE, body=BODY, url=URL):
    """Returns None on success, or an error string."""
    play_sound()
    try:
        if MAC:
            notify_mac(title, body, url)
        elif WINDOWS:
            notify_windows(title, body, url)
        else:
            return "only macOS and Windows are supported"
    except Exception as e:
        traceback.print_exc()
        return repr(e)
    return None

def run_app():
    import flet as ft

    def main(page:ft.Page):
        page.title="Notif test"
        page.padding=30
        status=ft.Text("")

        def fire():
            err=send()
            status.value = f"Error: {err}" if err else "Sent. Click the notification."
            page.update()

        def now(e):
            fire()

        def later(e):
            status.value = "Sending in 5 seconds... switch to another app"
            page.update()
            threading.Timer(5.0, fire).start()
 
        page.add(ft.Column(
            [
                ft.Text("Notification test", size=24),
                ft.Text("Clicking the notification opens YouTube"),
                ft.Button("Notify now", on_click=now),
                ft.Button("Notify in 5 seconds", on_click=later),
                status,
            ],
            spacing=14,
        ))

        if hasattr(ft,"run"):
            ft.run(main)
        else:
            ft.app(target=main)

if __name__ == "__main__":
    if len(sys.argv) >= 5 and sys.argv[1] == "--toast":
        run_toast(sys.argv[2], sys.argv[3], sys.argv[4])
        sys.exit(0)
    run_app()

