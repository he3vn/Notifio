def play_sound():
    try:
        if MAC:
            subprocess.Popen(["afplay", "/System/Library/Sounds/Glass.aiff"],
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        elif WINDOWS:
            import winsound
            winsound.MessageBeep(winsound.MB_ICONASTERISK)
    except Exception:
        traceback.print_exc()

def run_toast(title,body,url):
    import objc
    from AppKit import (NSApplication, NSApplicationActivationPolicyAccessory,NSColor, NSCursor, NSFont, NSMakeRect, NSPanel,NSScreen, NSTextField, NSView)

    W,H,MARGIN=360,78,14

    def open_url():
        subprocess.run(["open", url])
        os._exit(0)

    class ToastView(NSView):
        def acceptsFirstMouse_(self, event):
            return True

        def hitTest_(self,point):
            hit = objc.super(ToastView, self).hitTest_(point)
            return self if hit is not None else None

        def mouseDown_(self,event):
            open_url()

        def rightMouseDown_(self,event):
            os._exit(0)

        def resetCursorReacts(self):
            self.addCursorRect_cursor_(self.bounds(), NSCursor.pointingHandCursor())

    #I will let claude do the labels and the rest of these code i will work on the notification for mac
    def label(text, rect, size, bold, alpha, lines):
        f = NSTextField.alloc().initWithFrame_(rect)
        f.setStringValue_(str(text))
        f.setBezeled_(False)
        f.setDrawsBackground_(False)
        f.setEditable_(False)
        f.setSelectable_(False)
        f.setTextColor_(NSColor.colorWithCalibratedWhite_alpha_(1.0, alpha))
        f.setFont_(NSFont.boldSystemFontOfSize_(size) if bold else NSFont.systemFontOfSize_(size))
        cell = f.cell()
        cell.setWraps_(lines > 1)
        cell.setLineBreakMode_(0 if lines > 1 else 4)
        f.setMaximumNumberOfLines_(lines)
        return f
 
    app = NSApplication.sharedApplication()
    app.setActivationPolicy_(NSApplicationActivationPolicyAccessory)
 
    screen = (NSScreen.screens() or [NSScreen.mainScreen()])[0]
    frame = screen.visibleFrame()
    x = frame.origin.x + frame.size.width - W - MARGIN
    y = frame.origin.y + frame.size.height - H - MARGIN
 
    panel = NSPanel.alloc().initWithContentRect_styleMask_backing_defer_(
        NSMakeRect(x, y, W, H), 1 << 7, 2, False)  # borderless + non-activating
    panel.setLevel_(25)
    panel.setOpaque_(False)
    panel.setBackgroundColor_(NSColor.clearColor())
    panel.setHasShadow_(True)
    panel.setFloatingPanel_(True)
    panel.setHidesOnDeactivate_(False)
    panel.setReleasedWhenClosed_(False)
    panel.setCollectionBehavior_((1 << 0) | (1 << 4) | (1 << 8))
 
    view = ToastView.alloc().initWithFrame_(NSMakeRect(0, 0, W, H))
    view.setWantsLayer_(True)
    layer = view.layer()
    layer.setBackgroundColor_(NSColor.colorWithCalibratedWhite_alpha_(0.11, 0.97).CGColor())
    layer.setCornerRadius_(14.0)
    layer.setBorderWidth_(1.0)
    layer.setBorderColor_(NSColor.colorWithCalibratedWhite_alpha_(1.0, 0.14).CGColor())
    view.addSubview_(label(title, NSMakeRect(16, H - 32, W - 32, 18), 13, True, 1.0, 1))
    view.addSubview_(label(body, NSMakeRect(16, 10, W - 32, 34), 12, False, 0.72, 2))
    panel.setContentView_(view)
    panel.orderFrontRegardless()
 
    threading.Timer(7.0, lambda: os._exit(0)).start()  # auto-dismiss
    app.run()

def notify_mac(title,body,url):
    log = open(os.path.join(HERE, "toast.log"), "ab")
    subprocess.Popen([sys.executable, os.path.abspath(__file__), "--toast", title, body, url],stdin=subprocess.DEVNULL, stdout=log, stderr=log)

